function compactWorldSearch(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}

export function searchTrojanReachWorlds(query: string, limit = 12): TrojanReachWorld[] {
  const trimmed = compactWorldSearch(query);
  if (!trimmed) return TROJAN_REACH_WORLDS.slice(0, limit);
  const terms = trimmed.split(/\s+/);
  return TROJAN_REACH_WORLDS
    .map(world => {
      const haystack = compactWorldSearch([world.name, world.hex, world.subsector, world.uwp, world.remarks, world.allegianceName].join(' '));
      if (!terms.every(term => haystack.includes(term))) return null;
      const name = compactWorldSearch(world.name);
      const score = name === trimmed ? 0 : name.startsWith(trimmed) ? 1 : world.hex === query.trim() ? 2 : 3;
      return { world, score };
    })
    .filter((entry): entry is { world: TrojanReachWorld; score: number } => entry !== null)
    .sort((a, b) => a.score - b.score || a.world.name.localeCompare(b.world.name) || a.world.hex.localeCompare(b.world.hex))
    .slice(0, limit)
    .map(entry => entry.world);
}
